// Que es la programacion orientada a eventos

/*
    * La programación orientada a eventos es un paradigma de programación que se basa en la interacción de eventos
    * (como clicks de ratón, teclas pulsadas, etc.) para ejecutar código.
    * En lugar de ejecutar un programa de forma secuencial, el programa se ejecuta en respuesta a eventos.
    * Por ejemplo, en un programa de interfaz gráfica, el código se ejecuta en respuesta a eventos del usuario.
    * La programación orientada a eventos es común en aplicaciones de interfaz gráfica, juegos y servidores web.
*/

// En que consiste la programacion orientada a eventos

/*
    1. Toda acción que ejecute el sistema será en respuesta a los sucesos que
    acontezcan.
    2. A esos sucesos los llamamos eventos
    3. Las acciones a ejecutar, lo que programamos, son los manejadores
    4. A las fuentes de eventos las vamos a nombrar actores
*/

// Que es una cola de eventos

/*
    * Una cola de eventos es una estructura de datos que almacena eventos en orden de llegada.
    * Los eventos se pueden agregar a la cola y se pueden procesar en el mismo orden en que se agregaron.
    * Las colas de eventos se utilizan en programación orientada a eventos para manejar eventos de forma asíncrona.
    * Event Queue:
    Usamos una cola de eventos para poder proteger el orden de la ejecución de los eventos en
    un programa concurrente. Proteger la cola nos brinda mucha seguridad respecto a la
    concurrencia (pero no nos salva).
    Los handlers son secciones de código que saben cómo responder a la aparición de un
    evento.


*/
